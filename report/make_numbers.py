"""Write report/numbers.tex: every number quoted in the report, computed from results/ and the cached graphs.

Run from the repository root, after the experiments:
    python report/make_numbers.py --data-dir data
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.data import load_images  # noqa: E402
from src.graphs import FEATURE_NAMES, graph_stats  # noqa: E402

GROUPS = {"gcn_3feat": "gcnthree", "gcn": "gcn", "sage_raw": "sageraw", "sage": "sage",
          "lenet": "lenet", "cnn": "cnn"}


def fr(x: float, nd: int = 2) -> str:
    """French decimal comma, thin space as thousands separator."""
    s = f"{x:,.{nd}f}".replace(",", " ").replace(".", ",")
    return s.replace(" ", "\\,")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--results", default="results")
    p.add_argument("--data-dir", default="data")
    p.add_argument("--out", default="report/numbers.tex")
    args = p.parse_args()

    lines = ["% Generated by report/make_numbers.py -- do not edit by hand."]
    def cmd(name, value):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    runs = {}
    for g, m in GROUPS.items():
        rs = []
        for path in sorted(glob.glob(os.path.join(args.results, "mnist", f"{g}_seed*.json"))):
            with open(path) as f:
                rs.append(json.load(f))
        if not rs:
            print(f"warning: no runs for {g}")
            continue
        runs[g] = rs
        test = np.array([r["test_acc"] for r in rs]) * 100
        val = np.array([r["val_acc"] for r in rs]) * 100
        tr = np.array([r["train_acc_eval"] for r in rs]) * 100
        sd = lambda v: v.std(ddof=1) if len(v) > 1 else 0.0
        cmd(f"test{m}", fr(test.mean()))
        cmd(f"testsd{m}", fr(sd(test)))
        cmd(f"testmin{m}", fr(test.min()))
        cmd(f"testmax{m}", fr(test.max()))
        cmd(f"val{m}", fr(val.mean()))
        cmd(f"valsd{m}", fr(sd(val)))
        cmd(f"train{m}", fr(tr.mean()))
        cmd(f"seeds{m}", str(len(rs)))
        # Table cells: "mean ± sd" when several seeds were run, the single value otherwise
        cell = lambda v: f"{fr(v.mean())}\\pmv{{}}{fr(sd(v))}" if len(v) > 1 else fr(v.mean())
        cmd(f"testcell{m}", cell(test))
        cmd(f"valcell{m}", cell(val))
        cmd(f"params{m}", fr(rs[0]["n_params"], 0))
        cmd(f"bestep{m}", fr(np.mean([r["best_epoch"] for r in rs]), 1 if len(rs) > 1 else 0))
        cmd(f"sec{m}", fr(np.mean([np.mean([h["seconds"] for h in r["history"]]) for r in rs]), 0))
        cmd(f"min{m}", fr(np.mean([r["train_seconds"] for r in rs]) / 60, 0))

    # Per-class recall (mean over seeds) and the most frequent confusions of GraphSAGE
    _, _, _, y_te = load_images("mnist", args.data_dir)
    rows = []
    for g in ("gcn", "sage", "lenet", "cnn"):
        if g not in runs:
            continue
        rec = []
        for r in runs[g]:
            pred = np.load(os.path.join(args.results, "mnist", f"{r['run_name']}_test_preds.npy"))
            rec.append([(pred[y_te == c] == c).mean() * 100 for c in range(10)])
        rec = np.array(rec).mean(0)
        rows.append((g, rec))
        cmd(f"worstclass{GROUPS[g]}", str(int(rec.argmin())))
        cmd(f"worstrecall{GROUPS[g]}", fr(rec.min()))
        cmd(f"bestclass{GROUPS[g]}", str(int(rec.argmax())))
        cmd(f"bestrecall{GROUPS[g]}", fr(rec.max()))
    names = {"gcn": "GCN", "sage": "GraphSAGE", "lenet": "LeNet-5", "cnn": "CNN"}
    table = [" & ".join(["Modèle"] + [str(c) for c in range(10)]) + r" \\ \midrule"]
    for g, rec in rows:
        table.append(" & ".join([names[g]] + [fr(v, 1) for v in rec]) + r" \\")
    lines.append("\\newcommand{\\recalltable}{" + "\n".join(table) + "}")

    if "sage" in runs:
        cm = np.zeros((10, 10), int)
        for r in runs["sage"]:
            pred = np.load(os.path.join(args.results, "mnist", f"{r['run_name']}_test_preds.npy"))
            np.add.at(cm, (y_te, pred), 1)
        off = cm.copy()
        np.fill_diagonal(off, 0)
        top = np.dstack(np.unravel_index(np.argsort(off.ravel())[::-1][:3], off.shape))[0]
        for k, (t, pr) in enumerate(top, 1):
            cmd(f"confpair{'abc'[k - 1]}", f"{t}~$\\to$~{pr}")
            cmd(f"confcount{'abc'[k - 1]}", fr(off[t, pr] / len(runs["sage"]), 0))

    # Graph statistics and raw feature scales (training split)
    cache = os.path.join(args.data_dir, "graphs", "mnist_train_graphs.pt")
    graphs = torch.load(cache, weights_only=False)
    s = graph_stats(graphs)
    cmd("nodesmean", fr(s["nodes_mean"], 1))
    cmd("nodesmin", fr(s["nodes_min"], 0))
    cmd("nodesmax", fr(s["nodes_max"], 0))
    cmd("edgesmean", fr(s["undirected_edges_mean"], 1))
    cmd("degreemean", fr(s["degree_mean"], 2))
    x = torch.cat([g.x for g in graphs]).numpy()
    for j, name in enumerate(FEATURE_NAMES["mnist"]):
        key = name.replace("_", "")
        cmd(f"fmean{key}", fr(x[:, j].mean(), 3))
        cmd(f"fstd{key}", fr(x[:, j].std(), 3))

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines) - 1} macros written to {args.out}")


if __name__ == "__main__":
    main()
